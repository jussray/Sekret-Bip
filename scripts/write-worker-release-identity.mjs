import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';

const SHA_PATTERN = /^[0-9a-f]{40}$/i;
const OUTPUT_PATH = path.resolve('worker/release-identity.generated.ts');

function normalizeSha(value) {
  const sha = String(value ?? '').trim().toLowerCase();
  return SHA_PATTERN.test(sha) ? sha : null;
}

function gitHead() {
  try {
    return normalizeSha(execFileSync('git', ['rev-parse', 'HEAD'], {encoding: 'utf8'}));
  } catch {
    return null;
  }
}

export function resolveWorkerReleaseSha(env = process.env) {
  const workersBuildSha = normalizeSha(env.WORKERS_CI_COMMIT_SHA);
  if (env.WORKERS_CI_COMMIT_SHA && !workersBuildSha) {
    throw new Error('WORKERS_CI_COMMIT_SHA must be an exact 40-character Git commit SHA.');
  }

  const sha = workersBuildSha ?? gitHead();
  if (!sha) {
    throw new Error('Unable to resolve an exact Worker release SHA from Workers Builds or Git HEAD.');
  }
  return sha;
}

export function writeWorkerReleaseIdentity({env = process.env, outputPath = OUTPUT_PATH} = {}) {
  const sha = resolveWorkerReleaseSha(env);
  const source = `// Generated by scripts/write-worker-release-identity.mjs during Wrangler build.\nexport const WORKER_RELEASE_SHA = '${sha}' as const;\n`;
  fs.mkdirSync(path.dirname(outputPath), {recursive: true});
  fs.writeFileSync(outputPath, source, 'utf8');
  return sha;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  try {
    const sha = writeWorkerReleaseIdentity();
    console.log(`Stamped Worker runtime release SHA ${sha}.`);
  } catch (error) {
    console.error(error instanceof Error ? error.stack ?? error.message : String(error));
    process.exit(1);
  }
}
